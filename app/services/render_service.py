"""Deterministic FFmpeg renderer: timed scene clips + song (+ subtitles, intro/outro) -> MP4.

The filter graph is generated by ``build_render_plan`` (a pure function, unit tested) and saved
next to the output for reproducibility.
"""

from __future__ import annotations

import shutil
from dataclasses import dataclass, field
from pathlib import Path

from app.core.config import RenderPreset
from app.core.progress import report
from app.models.state import Gate
from app.pipeline.context import PipelineContext, PipelineError
from app.services.scene_assets import selected_file
from app.services.subtitles import write_subtitles
from app.utils.ffmpeg import has_audio, media_duration, run_ffmpeg
from app.utils.files import now_iso, write_json, write_text

SUBTITLE_STYLE = ("FontName=DejaVu Sans,FontSize=20,PrimaryColour=&H00FFFFFF,"
                  "OutlineColour=&H00000000,BorderStyle=1,Outline=2,Shadow=0,MarginV=28")


@dataclass
class Clip:
    path: Path
    duration: float  # scene duration on the timeline
    still: bool = False


@dataclass
class Segment:
    """Intro/outro clip played before/after the song."""

    path: Path
    duration: float
    has_audio: bool


@dataclass
class RenderPlan:
    inputs: list[list[str]]
    filter_complex: str
    output_args: list[str]
    total_duration: float
    xfade_offsets: list[float] = field(default_factory=list)

    def ffmpeg_args(self, output: Path) -> list[str]:
        args: list[str] = []
        for inp in self.inputs:
            args += inp
        return args + ["-filter_complex", self.filter_complex, *self.output_args, str(output)]


def _fit(preset: RenderPreset) -> str:
    w, h = preset.width, preset.height
    if preset.fit == "crop":
        return f"scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h}"
    return (f"scale={w}:{h}:force_original_aspect_ratio=decrease,"
            f"pad={w}:{h}:(ow-iw)/2:(oh-ih)/2:color=black")


def _video_norm(preset: RenderPreset) -> str:
    return f"{_fit(preset)},setsar=1,fps={preset.fps},format=yuv420p"


def _audio_norm() -> str:
    return "aresample=48000,aformat=sample_fmts=fltp:channel_layouts=stereo"


def build_render_plan(
    clips: list[Clip],
    song: Path,
    song_duration: float,
    preset: RenderPreset,
    *,
    subtitles_file: str | None = None,
    intro: Segment | None = None,
    outro: Segment | None = None,
) -> RenderPlan:
    if not clips:
        raise ValueError("nothing to render")
    xf = preset.crossfade if len(clips) > 1 else 0.0
    if xf and min(c.duration for c in clips) <= xf:
        xf = 0.0  # a scene shorter than the transition: fall back to hard cuts

    inputs: list[list[str]] = []
    graph: list[str] = []
    norm = _video_norm(preset)

    for i, clip in enumerate(clips):
        length = clip.duration + (xf if i < len(clips) - 1 else 0.0)
        if clip.still:
            inputs.append(["-loop", "1", "-framerate", str(preset.fps), "-t", f"{length:.3f}",
                           "-i", str(clip.path)])
        else:
            inputs.append(["-i", str(clip.path)])
        # Hold the last frame if the clip is short, then cut to exactly the needed length.
        graph.append(
            f"[{i}:v]{norm},tpad=stop_mode=clone:stop_duration={length:.3f},"
            f"trim=duration={length:.3f},setpts=PTS-STARTPTS[v{i}]"
        )

    offsets: list[float] = []
    if len(clips) == 1:
        graph.append("[v0]null[main_v]")
    elif xf:
        prev, t = "v0", 0.0
        for i in range(1, len(clips)):
            t += clips[i - 1].duration
            offsets.append(round(t, 3))
            out = "main_v" if i == len(clips) - 1 else f"x{i}"
            graph.append(f"[{prev}][v{i}]xfade=transition=fade:duration={xf:.3f}:"
                         f"offset={t:.3f}[{out}]")
            prev = out
    else:
        graph.append("".join(f"[v{i}]" for i in range(len(clips)))
                     + f"concat=n={len(clips)}:v=1:a=0[main_v]")

    if subtitles_file:
        graph.append(f"[main_v]subtitles=filename={subtitles_file}:"
                     f"force_style='{SUBTITLE_STYLE}'[main_vs]")
        main_v = "main_vs"
    else:
        main_v = "main_v"

    song_idx = len(inputs)
    inputs.append(["-i", str(song)])
    audio = f"[{song_idx}:a]atrim=duration={song_duration:.3f},asetpts=PTS-STARTPTS"
    if preset.loudnorm:
        audio += ",loudnorm=I=-14:TP=-1.5:LRA=11"
    graph.append(f"{audio},{_audio_norm()}[main_a]")

    parts: list[tuple[str, str]] = []
    total = song_duration

    def segment(seg: Segment, tag: str) -> tuple[str, str]:
        idx = len(inputs)
        inputs.append(["-i", str(seg.path)])
        graph.append(f"[{idx}:v]{norm},trim=duration={seg.duration:.3f},"
                     f"setpts=PTS-STARTPTS[{tag}_v]")
        if seg.has_audio:
            graph.append(f"[{idx}:a]atrim=duration={seg.duration:.3f},asetpts=PTS-STARTPTS,"
                         f"{_audio_norm()}[{tag}_a]")
        else:
            graph.append(f"anullsrc=r=48000:cl=stereo,atrim=duration={seg.duration:.3f},"
                         f"{_audio_norm()}[{tag}_a]")
        return f"{tag}_v", f"{tag}_a"

    if intro:
        parts.append(segment(intro, "intro"))
        total += intro.duration
    parts.append((main_v, "main_a"))
    if outro:
        parts.append(segment(outro, "outro"))
        total += outro.duration

    if len(parts) == 1:
        vout, aout = main_v, "main_a"
    else:
        graph.append("".join(f"[{v}][{a}]" for v, a in parts)
                     + f"concat=n={len(parts)}:v=1:a=1[vout][aout]")
        vout, aout = "vout", "aout"

    output_args = [
        "-map", f"[{vout}]", "-map", f"[{aout}]",
        "-c:v", "libx264", "-preset", preset.x264_preset, "-crf", str(preset.crf),
        "-pix_fmt", "yuv420p", "-r", str(preset.fps),
        "-c:a", "aac", "-b:a", preset.audio_bitrate, "-ar", "48000",
        "-movflags", "+faststart", "-t", f"{total:.3f}",
    ]
    return RenderPlan(inputs, ";\n".join(graph), output_args, round(total, 3), offsets)


def collect_clips(ctx: PipelineContext, preset: RenderPreset) -> list[Clip]:
    clips, missing = [], []
    for scene in ctx.storyboard().scenes:
        video = selected_file(ctx, scene.id, "video")
        image = selected_file(ctx, scene.id, "image")
        if video.is_file():
            clips.append(Clip(video, scene.duration))
        elif preset.allow_stills and image.is_file():
            clips.append(Clip(image, scene.duration, still=True))
        else:
            missing.append(scene.id)
    if missing:
        kind = "animation or image" if preset.allow_stills else "animation"
        raise PipelineError(f"scenes without a selected {kind}: {missing}")
    return clips


async def _segment(ctx: PipelineContext, p: Path | None) -> Segment | None:
    if p is None:
        return None
    path = ctx.resolve(p)
    if not path.is_file():
        raise PipelineError(f"intro/outro file not found: {path}")
    return Segment(path, await media_duration(path), await has_audio(path))


async def render(ctx: PipelineContext, preset_name: str = "preview") -> Path:
    presets = ctx.config.render_presets
    if preset_name not in presets:
        raise PipelineError(f"unknown preset '{preset_name}' (have: {', '.join(presets)})")
    preset = presets[preset_name]
    if not preset.allow_stills:
        ctx.require_gate(Gate.videos)
        ctx.require_gate(Gate.preview)

    paths = ctx.paths
    if not paths.song.is_file():
        raise PipelineError(f"no song; run: kidsvideo music {ctx.project_id}")
    storyboard = ctx.storyboard()
    clips = collect_clips(ctx, preset)
    subs = write_subtitles(ctx)

    out_dir = paths.render_dir(preset_name)
    out_dir.mkdir(parents=True, exist_ok=True)
    sub_name = None
    if preset.burn_subtitles:
        shutil.copy2(subs["bilingual"], out_dir / "bilingual.srt")
        sub_name = "bilingual.srt"  # relative: ffmpeg runs in out_dir, avoids path escaping

    plan = build_render_plan(
        clips, paths.song.resolve(), storyboard.duration, preset,
        subtitles_file=sub_name,
        intro=await _segment(ctx, preset.intro),
        outro=await _segment(ctx, preset.outro),
    )
    output = out_dir / "final.mp4"
    args = plan.ffmpeg_args(output.resolve())
    write_text(out_dir / "filter_graph.txt", plan.filter_complex + "\n")
    write_json(out_dir / "render.json", {
        "preset": preset_name, "settings": preset.model_dump(mode="json"),
        "created_at": now_iso(), "total_duration": plan.total_duration,
        "clips": [{"path": str(c.path), "duration": c.duration, "still": c.still}
                  for c in clips],
        "ffmpeg_args": args,
    })
    report("GENERATING", f"rendering {preset_name}")
    await run_ffmpeg(args, cwd=out_dir)

    final = paths.output_video(preset_name)
    final.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(output, final)
    return final
